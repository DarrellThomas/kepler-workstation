_N = len(_ALT)


def atmosphere_titan_hasi(alt_m):
    """Titan atmosphere from Huygens HASI data (linear/log-linear interpolation).

    Args:
        alt_m: altitude above surface in meters

    Returns:
        (rho, press, tempk) — density (kg/m³), pressure (Pa), temperature (K)
    """
    if alt_m <= _ALT[0]:
        return _DENS[0], _PRESS[0], _TEMP[0]
    if alt_m >= _ALT[-1]:
        # Exponential extrapolation above data ceiling
        scale_h = 296.8 * _TEMP[-1] / 1.352
        dalt = alt_m - _ALT[-1]
        tempk = _TEMP[-1]
        press = _PRESS[-1] * math.exp(-dalt / scale_h)
        rho = press / (296.8 * tempk)
        return rho, press, tempk

    # Binary search
    i = bisect.bisect_right(_ALT, alt_m) - 1
    if i >= _N - 1:
        i = _N - 2
    frac = (alt_m - _ALT[i]) / (_ALT[i + 1] - _ALT[i])
    tempk = _TEMP[i] + frac * (_TEMP[i + 1] - _TEMP[i])
    # Log-linear for pressure and density
    press = _PRESS[i] * math.exp(frac * math.log(_PRESS[i + 1] / _PRESS[i]))
    rho = _DENS[i] * math.exp(frac * math.log(_DENS[i + 1] / _DENS[i]))
    return rho, press, tempk
